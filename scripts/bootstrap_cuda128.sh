#!/usr/bin/env bash
# Public Linux bootstrap: CPU tools and a separate CUDA 12.8 model environment.
# Python/package downloads and public GitHub build sources require network access.
# This script does not fetch models, change drivers, or launch a model service.
set -euo pipefail
umask 077

ENV_ROOT=''
INDEX_URL=''
TRUSTED_HOST=''
PLAN=0
CPU_BUILD_FOR=''
MIRROR_ONLY=1
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd -P)"
PIP_HELPER="$SCRIPT_DIR/pip_index_install.py"
CUDA_PREFLIGHT="$SCRIPT_DIR/preflight_cuda128_build.py"
DEPENDENCY_PREFLIGHT="$SCRIPT_DIR/prepare_vllm_dependencies.py"
TORCH_PREPARE="$SCRIPT_DIR/prepare_torch_wheel.py"
die() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
usage() {
    printf '%s\n' \
        'Usage: bash bootstrap_cuda128.sh --env-root /existing/parent/target' \
        '       --index-url URL --trusted-host HOST [--cpu-build-for h200] [--plan]' \
        '       [--mirror-only | --allow-official-fallback] (default: mirror-only)' \
        'The target may already exist; its parent must exist. --plan is offline.' \
        'Optional: SHORE_CUDA128_HOME, CC, CXX, SHORE_BUILD_JOBS (default 4, CPU build 2).'
}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --env-root|--index-url|--trusted-host|--cpu-build-for)
            [ "$#" -ge 2 ] && [ -n "$2" ] && [[ "$2" != --* ]] || die "Missing value for $1"
            case "$1" in
                --env-root) ENV_ROOT="$2" ;;
                --index-url) INDEX_URL="$2" ;;
                --trusted-host) TRUSTED_HOST="$2" ;;
                --cpu-build-for) CPU_BUILD_FOR="$2" ;;
            esac
            shift 2 ;;
        --plan) PLAN=1; shift ;;
        --mirror-only) MIRROR_ONLY=1; shift ;;
        --allow-official-fallback) MIRROR_ONLY=0; shift ;;
        --help|-h) usage; exit 0 ;;
        *) die "Unknown argument: $1" ;;
    esac
done
[ -z "$CPU_BUILD_FOR" ] || [ "$CPU_BUILD_FOR" = h200 ] || die '--cpu-build-for currently accepts h200 only.'

[[ "$ENV_ROOT" == /* ]] || die '--env-root must be a nonempty absolute path.'
while [[ "$ENV_ROOT" == */ && "$ENV_ROOT" != / ]]; do ENV_ROOT="${ENV_ROOT%/}"; done
[ "$ENV_ROOT" != / ] || die 'The filesystem root cannot be --env-root.'
ROOT_NAME="$(basename -- "$ENV_ROOT")"
[[ "$ROOT_NAME" != . && "$ROOT_NAME" != .. ]] || die '--env-root must name a directory, not . or ...'
ROOT_PARENT="$(dirname -- "$ENV_ROOT")"
[ -d "$ROOT_PARENT" ] || die 'The parent of --env-root must already exist.'
ROOT_PARENT="$(cd -- "$ROOT_PARENT" && pwd -P)"
ENV_ROOT="${ROOT_PARENT%/}/$ROOT_NAME"
if [ -e "$ENV_ROOT" ] || [ -L "$ENV_ROOT" ]; then
    [ -d "$ENV_ROOT" ] || die '--env-root exists and is not a directory.'
    ENV_ROOT="$(cd -- "$ENV_ROOT" && pwd -P)"
fi
[ "$ENV_ROOT" != / ] || die '--env-root resolves to the filesystem root.'
TRIAL_ENV="$ENV_ROOT/.venv-trial"
MODEL_ENV="$ENV_ROOT/.venv-vllm-cu128"
ACTIVATION="$ENV_ROOT/activate_cuda128.sh"
OFFLINE_ACTIVATION="$ENV_ROOT/activate_h200_offline.sh"
BUILD_MANIFEST="$ENV_ROOT/cuda128-build-manifest.json"
[ ! -L "$BUILD_MANIFEST" ] || die 'Build manifest symlink preserved; choose a separate --env-root.'
for location in "$TRIAL_ENV" "$MODEL_ENV"; do
    [ ! -L "$location" ] || die "Environment symlink preserved; choose a separate --env-root: $location"
    if [ -e "$location" ]; then
        [ -d "$location" ] && [ -f "$location/pyvenv.cfg" ] && [ -x "$location/bin/python" ] || \
            die "Existing incomplete/non-venv path preserved: $location"
    fi
done
if [ -e "$ACTIVATION" ] || [ -L "$ACTIVATION" ]; then
    [ ! -L "$ACTIVATION" ] && [ -f "$ACTIVATION" ] || die "Existing activation path preserved: $ACTIVATION"
    IFS= read -r activation_marker < "$ACTIVATION" || true
    [ "${activation_marker:-}" = '# Generated by bootstrap_cuda128.sh.' ] || \
        die "Existing user activation file preserved: $ACTIVATION"
fi
if [ "$CPU_BUILD_FOR" = h200 ] && { [ -e "$OFFLINE_ACTIVATION" ] || [ -L "$OFFLINE_ACTIVATION" ]; }; then
    [ ! -L "$OFFLINE_ACTIVATION" ] && [ -f "$OFFLINE_ACTIVATION" ] || die 'Existing offline activation path is not a regular file.'
    IFS= read -r activation_marker < "$OFFLINE_ACTIVATION" || true
    [ "${activation_marker:-}" = '# Generated by bootstrap_cuda128.sh for offline H200.' ] || die 'Existing user offline activation file preserved.'
fi
if [ "$PLAN" -eq 1 ]; then
    printf 'CPU environment: %s\nModel environment: %s\nActivation file: %s\n' "$TRIAL_ENV" "$MODEL_ENV" "$ACTIVATION"
    printf '%s\n' \
        'Versions: Python 3.12; NumPy 2.1.3; SciPy 1.15.3; pytest 8.x.' \
        'Model stack: torch 2.11.0+cu128; torchvision 0.26.0+cu128; torchaudio 2.11.0+cu128;' \
        'vLLM 0.24.0 from source; transformers 5.8.0.' \
        'Default: only the supplied Python package index; exact CUDA12.8 packages remain pinned.' \
        'Official Torch/PyPI source links are used only with --allow-official-fallback.' \
        'Compilation may fetch public GitHub sources; GitHub login is not required.' \
        'Plan only: no directories created, installation, network, GPU, or model calls.'
    if [ "$CPU_BUILD_FOR" = h200 ]; then
        printf '%s\n' 'CPU build for H200: TORCH_CUDA_ARCH_LIST=9.0; no GPU/driver initialization required; GPU validation deferred.'
    else
        printf '%s\n' 'On-device installation: exactly four visible GPUs required for basic CUDA validation.'
    fi
    exit 0
fi
[ -n "$INDEX_URL" ] && [ -n "$TRUSTED_HOST" ] || die '--index-url and --trusted-host are required for installation.'
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] || die 'This profile requires Linux x86_64.'
for helper in "$PIP_HELPER" "$CUDA_PREFLIGHT" "$DEPENDENCY_PREFLIGHT" "$TORCH_PREPARE"; do
    [ -f "$helper" ] || die "Missing matching installer helper: $helper; use the complete install_all_dependencies.sh entry."
done
for executable in git curl getconf readlink; do
    command -v "$executable" >/dev/null || die "Missing build tool: $executable (install it through your platform environment)."
done
GLIBC_VERSION="$(getconf GNU_LIBC_VERSION)" || die 'Could not determine glibc version.'
[[ "$GLIBC_VERSION" =~ ^glibc[[:space:]]+([0-9]+)\.([0-9]+) ]] || die 'glibc >=2.28 is required.'
(( BASH_REMATCH[1] > 2 || (BASH_REMATCH[1] == 2 && BASH_REMATCH[2] >= 28) )) || die 'glibc >=2.28 is required.'
CC="$(type -P -- "${CC:-gcc}")" || die 'Missing C compiler; set CC to a GCC executable.'
CXX="$(type -P -- "${CXX:-g++}")" || die 'Missing C++ compiler; set CXX to a G++ executable.'
for compiler in "$CC" "$CXX"; do
    version="$("$compiler" -dumpfullversion -dumpversion)" || die "Cannot inspect compiler: $compiler"
    [[ "$version" =~ ^([0-9]+)\.([0-9]+) ]] || die "Cannot parse GCC/G++ version: $version"
    (( BASH_REMATCH[1] >= 11 && BASH_REMATCH[1] <= 14 )) && \
        (( BASH_REMATCH[1] > 11 || BASH_REMATCH[2] >= 3 )) || \
        die "CUDA 12.8 requires GCC/G++ 11.3 through 14 in this profile; found $compiler $version."
done
cuda_is_128() {
    [ -n "$1" ] && [ -x "$1/bin/nvcc" ] && \
        "$1/bin/nvcc" --version 2>/dev/null | grep -Eq 'release 12\.8([,[:space:]]|$)'
}
CUDA_ROOT=''
if [ -n "${SHORE_CUDA128_HOME:-}" ]; then
    cuda_is_128 "$SHORE_CUDA128_HOME" || die 'SHORE_CUDA128_HOME must point to a complete CUDA Toolkit 12.8 with bin/nvcc.'
    CUDA_ROOT="$SHORE_CUDA128_HOME"
else
    for candidate in "${CUDA_HOME:-}" /usr/local/cuda-12.8; do
        if cuda_is_128 "$candidate"; then CUDA_ROOT="$candidate"; break; fi
    done
    if [ -z "$CUDA_ROOT" ] && command -v nvcc >/dev/null; then
        candidate="$(dirname -- "$(dirname -- "$(readlink -f -- "$(command -v nvcc)")")")"
        if cuda_is_128 "$candidate"; then CUDA_ROOT="$candidate"; fi
    fi
fi
[ -n "$CUDA_ROOT" ] || die 'CUDA Toolkit 12.8 nvcc is missing. nvidia-smi does not verify the Toolkit. Install Toolkit 12.8 separately, then set SHORE_CUDA128_HOME to its directory and retry; no driver changes are made here.'
CUDA_HOME="$(cd -- "$CUDA_ROOT" && pwd -P)"
export CUDA_HOME CC CXX
export CUDACXX="$CUDA_HOME/bin/nvcc"
export CUDAHOSTCXX="$CXX" NVCC_CCBIN="$CXX"
export PATH="$CUDA_HOME/bin:$HOME/.local/bin:$PATH"
configure_cuda128_headers() {
    local directory include_dir='' library_dir=''
    for directory in "$CUDA_HOME/targets/x86_64-linux/include" "$CUDA_HOME/include"; do
        if [ -f "$directory/cuda.h" ] && [ -f "$directory/cuda_runtime.h" ] && [ -f "$directory/device_functions.h" ]; then
            include_dir="$directory"; break
        fi
    done
    [ -n "$include_dir" ] || die "CUDA 12.8 development headers are incomplete under $CUDA_HOME."
    for directory in "$CUDA_HOME/targets/x86_64-linux/lib" "$CUDA_HOME/lib64" "$CUDA_HOME/lib"; do
        if [ -f "$directory/libcudart.so" ]; then library_dir="$directory"; break; fi
    done
    [ -n "$library_dir" ] || die "CUDA 12.8 libcudart.so is missing under $CUDA_HOME."
    case "$CUDA_HOME" in *[[:space:]]*) die 'The CUDA toolchain path must not contain whitespace for the vLLM CMAKE_ARGS interface.' ;; esac
    export CUDA_INC_PATH="$include_dir" CUDA_LIB_PATH="$library_dir" CUDAToolkit_ROOT="$CUDA_HOME"
    export CUDA_PATH="$CUDA_HOME" CUDA_BIN_PATH="$CUDA_HOME" CUDA_NVCC_EXECUTABLE="$CUDA_HOME/bin/nvcc"
    export CMAKE_PREFIX_PATH="$CUDA_HOME/targets/x86_64-linux:$CUDA_HOME${CMAKE_PREFIX_PATH:+:$CMAKE_PREFIX_PATH}"
    # Explicit cache values supplement the legacy FindCUDA environment hints.
    export CMAKE_ARGS="${CMAKE_ARGS:-} -DCUDA_TOOLKIT_ROOT_DIR:PATH=$CUDA_HOME -DCUDA_TOOLKIT_INCLUDE:PATH=$include_dir -DCUDA_CUDART_LIBRARY:FILEPATH=$library_dir/libcudart.so"
    printf 'CUDA development include: %s\nCUDA runtime library: %s\n' "$include_dir" "$library_dir/libcudart.so"
}
configure_cuda128_headers
configure_cuda128_libraries() {
    local directory
    local -a library_dirs=() inherited_dirs=()
    for directory in "$CUDA_HOME/lib64" "$CUDA_HOME/lib" "$CUDA_HOME/targets/x86_64-linux/lib"; do
        [ ! -d "$directory" ] || library_dirs+=("$directory")
    done
    IFS=: read -r -a inherited_dirs <<< "${LD_LIBRARY_PATH:-}"
    for directory in "${inherited_dirs[@]}"; do
        case "$directory/" in */stubs/*|/) ;; *) library_dirs+=("$directory") ;; esac
    done
    if [ "${#library_dirs[@]}" -gt 0 ]; then
        LD_LIBRARY_PATH="$(IFS=:; printf '%s' "${library_dirs[*]}")"
        export LD_LIBRARY_PATH
    else
        unset LD_LIBRARY_PATH
    fi
}
configure_cuda128_libraries
