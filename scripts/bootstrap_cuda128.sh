if [ "$CPU_BUILD_FOR" = h200 ]; then DEFAULT_BUILD_JOBS=2; fi
export MAX_JOBS="${SHORE_BUILD_JOBS:-$DEFAULT_BUILD_JOBS}" NVCC_THREADS=1
[[ "$MAX_JOBS" =~ ^[1-9][0-9]*$ ]] || die 'SHORE_BUILD_JOBS must be a positive integer.'
export VLLM_TARGET_DEVICE=cuda VLLM_USE_PRECOMPILED=0 VLLM_USE_PRECOMPILED_RUST=0
export VLLM_USE_RUST_FRONTEND=0 VLLM_REQUIRE_RUST_FRONTEND=0 VLLM_VERSION_OVERRIDE=0.24.0
export GIT_TERMINAL_PROMPT=0
if [ "$CPU_BUILD_FOR" = h200 ]; then
    export TORCH_CUDA_ARCH_LIST=9.0
    export FLASHINFER_CUDA_ARCH_LIST=9.0a TVM_FFI_CUDA_ARCH_LIST=9.0a
    [ -x "$CUDA_HOME/bin/ptxas" ] && "$CUDA_HOME/bin/ptxas" --version | grep -Eq 'release 12\.8([,[:space:]]|$)' || \
        die 'H200 offline builds require CUDA Toolkit 12.8 bin/ptxas; Triton must not fall back to a different bundled assembler.'
    export TRITON_PTXAS_PATH="$CUDA_HOME/bin/ptxas"
fi

pip_install() {
    local interpreter="$1"
    shift
    local -a source_args=()
    if [ "$MIRROR_ONLY" -eq 1 ]; then source_args+=(--mirror-only); fi
    "$interpreter" "$PIP_HELPER" --python "$interpreter" \
        --index-url "$INDEX_URL" --trusted-host "$TRUSTED_HOST" \
        --log-dir "$ENV_ROOT/pip-logs" "${source_args[@]}" -- "$@"
}
if ! command -v uv >/dev/null; then
    BOOTSTRAP_PYTHON="$(command -v python3 || command -v python)" || die 'Install Python with pip, or uv, before retrying.'
    "$BOOTSTRAP_PYTHON" -m pip --version >/dev/null || die 'The bootstrap Python has no pip; install pip or uv through your platform environment.'
    pip_install "$BOOTSTRAP_PYTHON" --user uv
    hash -r
fi
command -v uv >/dev/null || die 'uv installation completed but uv is not on PATH; add your Python user-base bin directory and retry.'
mkdir -p -- "$ENV_ROOT"
# Keep managed interpreters on the same persistent storage as the environments.
export UV_PYTHON_INSTALL_DIR="${UV_PYTHON_INSTALL_DIR:-$ENV_ROOT/.tools/python}"
export UV_CACHE_DIR="${UV_CACHE_DIR:-$ENV_ROOT/.cache/uv}"
export UV_LINK_MODE=copy
REUSE_H200_BUILD=0
if [ -z "$CPU_BUILD_FOR" ] && { [ -e "$BUILD_MANIFEST" ] || [ -L "$BUILD_MANIFEST" ]; }; then
    die 'A CPU-target build manifest exists here; preserve the H200 environment and choose a fresh --env-root for on-device installation.'
fi
if [ "$CPU_BUILD_FOR" = h200 ] && { [ -d "$MODEL_ENV" ] || [ -e "$BUILD_MANIFEST" ] || [ -L "$BUILD_MANIFEST" ]; }; then
    [ -x "$MODEL_ENV/bin/python" ] || die 'Existing CPU build state has no model Python; preserve it and choose a fresh --env-root.'
    REUSE_H200_BUILD="$("$MODEL_ENV/bin/python" - "$ENV_ROOT" <<'PY'
# BEGIN H200_PROFILE_GUARD
import hashlib, json, pathlib, sys
root = pathlib.Path(sys.argv[1]).resolve()
manifest_path = root / 'cuda128-build-manifest.json'
model_env = root / '.venv-vllm-cu128'
installed = any(model_env.glob('lib/python*/site-packages/vllm-*.dist-info'))

def refuse(message):
    raise SystemExit(message + '; preserve this environment and choose a fresh --env-root.')

if manifest_path.is_symlink():
    refuse('Build manifest symlinks are not accepted')
if not manifest_path.exists():
    if installed:
        refuse('Existing vLLM has no completed H200 build manifest')
    print('0')
    raise SystemExit(0)
try:
    manifest = json.loads(manifest_path.read_text())
except (OSError, ValueError) as error:
    refuse('Cannot read the existing H200 build manifest: ' + str(error))
expected = {'schema_version':'1.0.0', 'target':'h200', 'target_cuda_arch':'9.0',
            'torch_cuda':'12.8', 'build_host':'cpu',
            'gpu_validation_performed':False, 'model_loaded':False}
if not isinstance(manifest, dict) or any(type(manifest.get(k)) is not type(v)
                                         or manifest.get(k) != v for k, v in expected.items()):
    refuse('Existing manifest belongs to another build profile')
if not installed:
    if manifest.get('cpu_stage_completed') is True:
        refuse('A completed H200 build is missing its installed vLLM')
    print('0')
    raise SystemExit(0)
if manifest.get('cpu_stage_completed') is not True:
    refuse('Existing vLLM belongs to an incomplete CPU build')
records = manifest.get('stable_extensions')
if not isinstance(records, list) or not records:
    refuse('Completed H200 manifest has no stable-extension fingerprints')
stems, seen = set(), set()
for item in records:
    if not isinstance(item, dict) or not isinstance(item.get('path'), str):
        refuse('Malformed stable-extension fingerprint')
    relative = pathlib.PurePosixPath(item['path'])
    path = (root / relative).resolve()
    stem = item.get('stem')
    if (relative.is_absolute() or not path.is_relative_to(model_env.resolve()) or path in seen
            or stem not in ('_C_stable_libtorch', '_moe_C_stable_libtorch')
            or not path.name.startswith(stem) or path.suffix != '.so'):
        refuse('Invalid stable-extension fingerprint path')
    seen.add(path)
    try:
        digest = hashlib.sha256()
        with path.open('rb') as source:
            for block in iter(lambda: source.read(4 * 1024 * 1024), b''):
                digest.update(block)
        if type(item.get('size')) is not int or path.stat().st_size != item['size'] or digest.hexdigest() != item.get('sha256'):
            refuse('Stable-extension bytes differ from the completed H200 build')
    except OSError:
        refuse('A completed H200 stable extension is missing')
    stems.add(stem)
if stems != {'_C_stable_libtorch', '_moe_C_stable_libtorch'}:
    refuse('Both completed H200 stable extensions must be fingerprinted')
print('1')
# END H200_PROFILE_GUARD
PY
)" || die 'Existing model build cannot be safely reused.'
fi
for location in "$TRIAL_ENV" "$MODEL_ENV"; do
    if [ ! -e "$location" ]; then uv venv --python 3.12 "$location"; fi
    "$location/bin/python" -c 'import sys; assert sys.prefix != sys.base_prefix, "Expected a virtual environment"; assert sys.version_info[:2] == (3, 12), "Python 3.12 is required"'
    "$location/bin/python" -m ensurepip --upgrade
done
"$MODEL_ENV/bin/python" -c 'import pathlib, sysconfig; assert (pathlib.Path(sysconfig.get_path("include")) / "Python.h").is_file(), "Python 3.12 development headers (Python.h) are required"'
if [ "$CPU_BUILD_FOR" = h200 ] && [ "$REUSE_H200_BUILD" -eq 0 ]; then
    "$MODEL_ENV/bin/python" - "$BUILD_MANIFEST" "$CUDA_HOME" "$CXX" "$CC" <<'PY'
import json, pathlib, sys
p = {'schema_version':'1.0.0','target':'h200','target_cuda_arch':'9.0','torch_cuda':'12.8',
     'build_host':'cpu','cpu_stage_completed':False,'gpu_validation_performed':False,
     'model_loaded':False,'cuda_home':sys.argv[2],'cxx':sys.argv[3],'cc':sys.argv[4],
     'triton_ptxas':str(pathlib.Path(sys.argv[2])/'bin/ptxas')}
pathlib.Path(sys.argv[1]).write_text(json.dumps(p,indent=2)+'\n')
PY
fi
LOG_ROOT="$(mktemp -d "$ENV_ROOT/bootstrap-cu128-logs.XXXXXXXX")"
CONSTRAINTS="$LOG_ROOT/constraints-cu128.txt"
printf '%s\n' 'torch==2.11.0+cu128' 'torchvision==0.26.0+cu128' 'torchaudio==2.11.0+cu128' 'transformers==5.8.0' > "$CONSTRAINTS"
printf '%s\n' 'openai>=2.0.0,<3' >> "$CONSTRAINTS"
export FETCHCONTENT_BASE_DIR="$ENV_ROOT/.cache/vllm-fetch"
case "$FETCHCONTENT_BASE_DIR" in *[[:space:]]*) die 'The build cache path must not contain whitespace for the vLLM CMAKE_ARGS interface.' ;; esac
export CMAKE_ARGS="${CMAKE_ARGS:-} -DFETCHCONTENT_BASE_DIR:PATH=$FETCHCONTENT_BASE_DIR"
mkdir -p -- "$FETCHCONTENT_BASE_DIR"
if [ "$MIRROR_ONLY" -eq 1 ]; then
    printf '%s\n' 'Python package index: specified mirror only; no official Torch downloader, extra wheel links or PyPI fallback.'
    printf '%s\n' 'Conda, managed Python, CMake build sources and non-pip FlashInfer assets are separate network resources.'
else
    printf '%s\n' 'Official fallback explicitly enabled; official PyTorch/PyPI links and public GitHub build sources require network access.'
fi
pip_install "$TRIAL_ENV/bin/python" 'numpy==2.1.3' 'scipy==1.15.3' 'pytest>=8,<9'
pip_install "$MODEL_ENV/bin/python" --upgrade pip
# BEGIN TORCH_WHEEL_SELECTION
if [ "$MIRROR_ONLY" -eq 1 ]; then
    printf '\n[SHORE] Install exact CUDA12.8 Torch/vision/audio from the specified mirror only.\n'
    if ! pip_install "$MODEL_ENV/bin/python" -c "$CONSTRAINTS" --only-binary=:all: \
        'torch==2.11.0+cu128' 'torchvision==0.26.0+cu128' 'torchaudio==2.11.0+cu128'; then
        die 'Mirror-only Torch installation failed. Inspect the pip log: the mirror must provide Python3.12/Linux x86_64 compatible torch2.11.0+cu128, torchvision0.26.0+cu128 and torchaudio2.11.0+cu128. Network failures and missing artifacts require mirror/platform repair; no CUDA version was substituted or official Torch downloader invoked. Existing wheelhouse/.part files were preserved.'
    fi
else
TORCH_REQUIREMENT='torch==2.11.0+cu128'
if ! "$MODEL_ENV/bin/python" -I -c 'import importlib.metadata as m; assert m.version("torch")=="2.11.0+cu128"' >/dev/null 2>&1; then
    printf '\n[SHORE] Persist the exact Torch wheel and verify its SHA256 before installation.\n'
    "$MODEL_ENV/bin/python" "$TORCH_PREPARE" --output-dir "$ENV_ROOT/wheelhouse"
    TORCH_REQUIREMENT="$ENV_ROOT/wheelhouse/torch-2.11.0+cu128-cp312-cp312-manylinux_2_28_x86_64.whl"
else
    printf '\n[SHORE] Reuse the installed torch2.11.0+cu128; no Torch wheel download requested.\n'
fi
pip_install "$MODEL_ENV/bin/python" -c "$CONSTRAINTS" \
    --find-links https://download.pytorch.org/whl/cu128/torch/ \
    --find-links https://download.pytorch.org/whl/cu128/torchvision/ \
    --find-links https://download.pytorch.org/whl/cu128/torchaudio/ \
    "$TORCH_REQUIREMENT" 'torchvision==0.26.0+cu128' 'torchaudio==2.11.0+cu128'
fi
# END TORCH_WHEEL_SELECTION
if [ "$CPU_BUILD_FOR" = h200 ]; then
    "$MODEL_ENV/bin/python" - <<'PY'
