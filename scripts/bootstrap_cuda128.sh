#!/usr/bin/env bash
# Public Linux bootstrap: CPU tools and a separate CUDA 12.8 model environment.
# Python/package downloads and public GitHub build sources require network access.
# This script does not fetch models, change drivers, or launch a model service.
set -euo pipefail
umask 077

ENV_ROOT=''
INDEX_URL=''
TRUSTED_HOST=''
PLAN=0
die() { printf 'ERROR: %s\n' "$*" >&2; exit 2; }
usage() {
    printf '%s\n' \
        'Usage: bash bootstrap_cuda128.sh --env-root /existing/parent/target' \
        '       --index-url URL --trusted-host HOST [--plan]' \
        'The target may already exist; its parent must exist. --plan is offline.' \
        'Optional: SHORE_CUDA128_HOME, CC, CXX, SHORE_BUILD_JOBS (default 4).'
}
while [ "$#" -gt 0 ]; do
    case "$1" in
        --env-root|--index-url|--trusted-host)
            [ "$#" -ge 2 ] && [ -n "$2" ] && [[ "$2" != --* ]] || die "Missing value for $1"
            case "$1" in
                --env-root) ENV_ROOT="$2" ;;
                --index-url) INDEX_URL="$2" ;;
                --trusted-host) TRUSTED_HOST="$2" ;;
            esac
            shift 2 ;;
        --plan) PLAN=1; shift ;;
        --help|-h) usage; exit 0 ;;
        *) die "Unknown argument: $1" ;;
    esac
done

[[ "$ENV_ROOT" == /* ]] || die '--env-root must be a nonempty absolute path.'
while [[ "$ENV_ROOT" == */ && "$ENV_ROOT" != / ]]; do ENV_ROOT="${ENV_ROOT%/}"; done
[ "$ENV_ROOT" != / ] || die 'The filesystem root cannot be --env-root.'
ROOT_NAME="$(basename -- "$ENV_ROOT")"
[[ "$ROOT_NAME" != . && "$ROOT_NAME" != .. ]] || die '--env-root must name a directory, not . or ...'
ROOT_PARENT="$(dirname -- "$ENV_ROOT")"
[ -d "$ROOT_PARENT" ] || die 'The parent of --env-root must already exist.'
ROOT_PARENT="$(cd -- "$ROOT_PARENT" && pwd -P)"
ENV_ROOT="${ROOT_PARENT%/}/$ROOT_NAME"
if [ -e "$ENV_ROOT" ] || [ -L "$ENV_ROOT" ]; then
    [ -d "$ENV_ROOT" ] || die '--env-root exists and is not a directory.'
    ENV_ROOT="$(cd -- "$ENV_ROOT" && pwd -P)"
fi
[ "$ENV_ROOT" != / ] || die '--env-root resolves to the filesystem root.'
TRIAL_ENV="$ENV_ROOT/.venv-trial"
MODEL_ENV="$ENV_ROOT/.venv-vllm-cu128"
ACTIVATION="$ENV_ROOT/activate_cuda128.sh"
for location in "$TRIAL_ENV" "$MODEL_ENV"; do
    [ ! -L "$location" ] || die "Environment symlink preserved; choose a separate --env-root: $location"
    if [ -e "$location" ]; then
        [ -d "$location" ] && [ -f "$location/pyvenv.cfg" ] && [ -x "$location/bin/python" ] || \
            die "Existing incomplete/non-venv path preserved: $location"
    fi
done
if [ -e "$ACTIVATION" ] || [ -L "$ACTIVATION" ]; then
    [ ! -L "$ACTIVATION" ] && [ -f "$ACTIVATION" ] || die "Existing activation path preserved: $ACTIVATION"
    IFS= read -r activation_marker < "$ACTIVATION" || true
    [ "${activation_marker:-}" = '# Generated by bootstrap_cuda128.sh.' ] || \
        die "Existing user activation file preserved: $ACTIVATION"
fi
if [ "$PLAN" -eq 1 ]; then
    printf 'CPU environment: %s\nModel environment: %s\nActivation file: %s\n' "$TRIAL_ENV" "$MODEL_ENV" "$ACTIVATION"
    printf '%s\n' \
        'Versions: Python 3.12; NumPy 2.1.3; SciPy 1.15.3; pytest 8.x.' \
        'Model stack: torch 2.11.0+cu128; torchvision 0.26.0+cu128; torchaudio 2.11.0+cu128;' \
        'vLLM 0.24.0 from source; transformers 5.8.0; exactly four visible GPUs.' \
        'Actual installation uses the supplied package index plus official PyTorch/PyPI source links.' \
        'Compilation may fetch public GitHub sources; GitHub login is not required.' \
        'Plan only: no directories created, installation, network, GPU, or model calls.'
    exit 0
fi
[ -n "$INDEX_URL" ] && [ -n "$TRUSTED_HOST" ] || die '--index-url and --trusted-host are required for installation.'
[ "$(uname -s)" = Linux ] && [ "$(uname -m)" = x86_64 ] || die 'This profile requires Linux x86_64.'
for executable in git curl getconf readlink; do
    command -v "$executable" >/dev/null || die "Missing build tool: $executable (install it through your platform environment)."
done
GLIBC_VERSION="$(getconf GNU_LIBC_VERSION)" || die 'Could not determine glibc version.'
[[ "$GLIBC_VERSION" =~ ^glibc[[:space:]]+([0-9]+)\.([0-9]+) ]] || die 'glibc >=2.28 is required.'
(( BASH_REMATCH[1] > 2 || (BASH_REMATCH[1] == 2 && BASH_REMATCH[2] >= 28) )) || die 'glibc >=2.28 is required.'
CC="$(type -P -- "${CC:-gcc}")" || die 'Missing C compiler; set CC to a GCC executable.'
CXX="$(type -P -- "${CXX:-g++}")" || die 'Missing C++ compiler; set CXX to a G++ executable.'
for compiler in "$CC" "$CXX"; do
    version="$("$compiler" -dumpfullversion -dumpversion)" || die "Cannot inspect compiler: $compiler"
    [[ "$version" =~ ^([0-9]+)\.([0-9]+) ]] || die "Cannot parse GCC/G++ version: $version"
    (( BASH_REMATCH[1] >= 11 && BASH_REMATCH[1] <= 14 )) && \
        (( BASH_REMATCH[1] > 11 || BASH_REMATCH[2] >= 3 )) || \
        die "CUDA 12.8 requires GCC/G++ 11.3 through 14 in this profile; found $compiler $version."
done
cuda_is_128() {
    [ -n "$1" ] && [ -x "$1/bin/nvcc" ] && \
        "$1/bin/nvcc" --version 2>/dev/null | grep -Eq 'release 12\.8([,[:space:]]|$)'
}
CUDA_ROOT=''
if [ -n "${SHORE_CUDA128_HOME:-}" ]; then
    cuda_is_128 "$SHORE_CUDA128_HOME" || die 'SHORE_CUDA128_HOME must point to a complete CUDA Toolkit 12.8 with bin/nvcc.'
    CUDA_ROOT="$SHORE_CUDA128_HOME"
else
    for candidate in "${CUDA_HOME:-}" /usr/local/cuda-12.8; do
        if cuda_is_128 "$candidate"; then CUDA_ROOT="$candidate"; break; fi
    done
    if [ -z "$CUDA_ROOT" ] && command -v nvcc >/dev/null; then
        candidate="$(dirname -- "$(dirname -- "$(readlink -f -- "$(command -v nvcc)")")")"
        if cuda_is_128 "$candidate"; then CUDA_ROOT="$candidate"; fi
    fi
fi
[ -n "$CUDA_ROOT" ] || die 'CUDA Toolkit 12.8 nvcc is missing. nvidia-smi does not verify the Toolkit. Install Toolkit 12.8 separately, then set SHORE_CUDA128_HOME to its directory and retry; no driver changes are made here.'
CUDA_HOME="$(cd -- "$CUDA_ROOT" && pwd -P)"
export CUDA_HOME CC CXX
export CUDACXX="$CUDA_HOME/bin/nvcc"
export CUDAHOSTCXX="$CXX" NVCC_CCBIN="$CXX"
export PATH="$CUDA_HOME/bin:$HOME/.local/bin:$PATH"
configure_cuda128_libraries() {
    local directory
    local -a library_dirs=() inherited_dirs=()
    for directory in "$CUDA_HOME/lib64" "$CUDA_HOME/lib" "$CUDA_HOME/targets/x86_64-linux/lib"; do
        [ ! -d "$directory" ] || library_dirs+=("$directory")
    done
    IFS=: read -r -a inherited_dirs <<< "${LD_LIBRARY_PATH:-}"
    for directory in "${inherited_dirs[@]}"; do
        case "$directory/" in */stubs/*|/) ;; *) library_dirs+=("$directory") ;; esac
    done
    if [ "${#library_dirs[@]}" -gt 0 ]; then
        LD_LIBRARY_PATH="$(IFS=:; printf '%s' "${library_dirs[*]}")"
        export LD_LIBRARY_PATH
    else
        unset LD_LIBRARY_PATH
    fi
}
configure_cuda128_libraries
export MAX_JOBS="${SHORE_BUILD_JOBS:-4}" NVCC_THREADS=1
[[ "$MAX_JOBS" =~ ^[1-9][0-9]*$ ]] || die 'SHORE_BUILD_JOBS must be a positive integer.'
export VLLM_TARGET_DEVICE=cuda VLLM_USE_PRECOMPILED=0 VLLM_USE_PRECOMPILED_RUST=0
export VLLM_USE_RUST_FRONTEND=0 VLLM_REQUIRE_RUST_FRONTEND=0 VLLM_VERSION_OVERRIDE=0.24.0
export GIT_TERMINAL_PROMPT=0

pip_install() {
    local interpreter="$1"
    shift
    env -u PIP_EXTRA_INDEX_URL -u PIP_INDEX_URL PIP_CONFIG_FILE=/dev/null \
        "$interpreter" -m pip install "$@" \
        --index-url "$INDEX_URL" --trusted-host "$TRUSTED_HOST" \
        --no-cache-dir --timeout 600 --retries 5
}
if ! command -v uv >/dev/null; then
    BOOTSTRAP_PYTHON="$(command -v python3 || command -v python)" || die 'Install Python with pip, or uv, before retrying.'
    "$BOOTSTRAP_PYTHON" -m pip --version >/dev/null || die 'The bootstrap Python has no pip; install pip or uv through your platform environment.'
    pip_install "$BOOTSTRAP_PYTHON" --user uv
    hash -r
fi
command -v uv >/dev/null || die 'uv installation completed but uv is not on PATH; add your Python user-base bin directory and retry.'
mkdir -p -- "$ENV_ROOT"
# Keep managed interpreters on the same persistent storage as the environments.
export UV_PYTHON_INSTALL_DIR="${UV_PYTHON_INSTALL_DIR:-$ENV_ROOT/.tools/python}"
export UV_CACHE_DIR="${UV_CACHE_DIR:-$ENV_ROOT/.cache/uv}"
export UV_LINK_MODE=copy
for location in "$TRIAL_ENV" "$MODEL_ENV"; do
    if [ ! -e "$location" ]; then uv venv --python 3.12 "$location"; fi
    "$location/bin/python" -c 'import sys; assert sys.prefix != sys.base_prefix, "Expected a virtual environment"; assert sys.version_info[:2] == (3, 12), "Python 3.12 is required"'
    "$location/bin/python" -m ensurepip --upgrade
done
"$MODEL_ENV/bin/python" -c 'import pathlib, sysconfig; assert (pathlib.Path(sysconfig.get_path("include")) / "Python.h").is_file(), "Python 3.12 development headers (Python.h) are required"'
LOG_ROOT="$(mktemp -d "$ENV_ROOT/bootstrap-cu128-logs.XXXXXXXX")"
CONSTRAINTS="$LOG_ROOT/constraints-cu128.txt"
printf '%s\n' 'torch==2.11.0+cu128' 'torchvision==0.26.0+cu128' 'torchaudio==2.11.0+cu128' 'transformers==5.8.0' > "$CONSTRAINTS"
printf '%s\n' 'Packages use your supplied index; official PyTorch/PyPI links and public GitHub build sources also require network access.'
pip_install "$TRIAL_ENV/bin/python" 'numpy==2.1.3' 'scipy==1.15.3' 'pytest>=8,<9'
pip_install "$MODEL_ENV/bin/python" --upgrade pip
pip_install "$MODEL_ENV/bin/python" -c "$CONSTRAINTS" \
    --find-links https://download.pytorch.org/whl/cu128/torch/ \
    --find-links https://download.pytorch.org/whl/cu128/torchvision/ \
    --find-links https://download.pytorch.org/whl/cu128/torchaudio/ \
    'torch==2.11.0+cu128' 'torchvision==0.26.0+cu128' 'torchaudio==2.11.0+cu128'
"$MODEL_ENV/bin/python" - <<'PY'
import torch
assert torch.version.cuda == "12.8", torch.version.cuda
assert torch.cuda.is_available(), "CUDA initialization failed"
assert torch.cuda.device_count() == 4, "Expected exactly four allocated visible GPUs"
for i in range(torch.cuda.device_count()):
    props = torch.cuda.get_device_properties(i)
    with torch.cuda.device(i):
        x = torch.ones((128, 128), device=f"cuda:{i}", dtype=torch.bfloat16)
        assert bool(torch.all(x @ x == 128).item()), "BF16 matrix product disagreed"
        torch.cuda.synchronize()
    print("BF16 passed:", i, props.name, "GiB:", round(props.total_memory / 2**30, 2),
          "compute capability:", torch.cuda.get_device_capability(i))
PY
TORCH_CUDA_ARCH_LIST="$("$MODEL_ENV/bin/python" -c 'import torch; print(";".join(sorted({"%d.%d" % torch.cuda.get_device_capability(i) for i in range(torch.cuda.device_count())})))')"
export TORCH_CUDA_ARCH_LIST
pip_install "$MODEL_ENV/bin/python" -c "$CONSTRAINTS" \
    'cmake>=3.26.1' ninja 'packaging>=24.2' 'setuptools>=77.0.3,<81' \
    'setuptools-scm>=8' 'setuptools-rust>=1.9' wheel 'jinja2>=3.1.6' regex build \
    'protobuf>=5.29.6,!=6.30.*,!=6.31.*,!=6.32.*,!=6.33.0.*,!=6.33.1.*,!=6.33.2.*,!=6.33.3.*,!=6.33.4.*'
pip_install "$MODEL_ENV/bin/python" -c "$CONSTRAINTS" \
    --find-links https://pypi.org/simple/vllm/ --no-binary=vllm --no-build-isolation \
    'vllm==0.24.0' 'transformers==5.8.0'
"$TRIAL_ENV/bin/python" -m pip check
"$MODEL_ENV/bin/python" -m pip check
"$MODEL_ENV/bin/python" - <<'PY'
import importlib.metadata as md
import torch
import vllm._C_stable_libtorch
import vllm._moe_C_stable_libtorch
from vllm.reasoning import ReasoningParserManager
assert torch.version.cuda == "12.8", torch.version.cuda
assert md.version("vllm").split("+")[0] == "0.24.0", md.version("vllm")
assert md.version("transformers") == "5.8.0", md.version("transformers")
ReasoningParserManager.get_reasoning_parser("qwen3")
print("Installed:", {name: md.version(name) for name in ("torch", "vllm", "transformers")})
PY
"$MODEL_ENV/bin/vllm" serve --help > "$LOG_ROOT/serve-help.txt"
"$TRIAL_ENV/bin/python" -m pip freeze > "$LOG_ROOT/cpu-freeze.txt"
"$MODEL_ENV/bin/python" -m pip freeze > "$LOG_ROOT/model-freeze.txt"
{
    printf '%s\n' '# Generated by bootstrap_cuda128.sh.' '# Source this file in each new terminal before using the model environment.'
    printf 'source %q\n' "$MODEL_ENV/bin/activate"
    printf 'export CUDA_HOME=%q\n' "$CUDA_HOME"
    printf 'export CUDACXX=%q\n' "$CUDA_HOME/bin/nvcc"
    printf 'export CC=%q CXX=%q CUDAHOSTCXX=%q NVCC_CCBIN=%q\n' "$CC" "$CXX" "$CXX" "$CXX"
    printf '%s\n' 'export PATH="$CUDA_HOME/bin:$PATH"' '# Keep real Toolkit libraries ahead of inherited paths; exclude stub drivers.'
    declare -f configure_cuda128_libraries
    printf '%s\n' 'configure_cuda128_libraries' 'unset -f configure_cuda128_libraries' 'export VLLM_USE_RUST_FRONTEND=0'
} > "$ACTIVATION"
# Apply the same Toolkit selection to the final checks in this process.
source "$ACTIVATION"
"$CUDA_HOME/bin/nvcc" --version > "$LOG_ROOT/nvcc-version.txt"
printf '\nInstallation and basic CUDA/import checks passed.\nCPU: %s/bin/python\nActivate model environment: source %q\nDiagnostics: %s\n' "$TRIAL_ENV" "$ACTIVATION" "$LOG_ROOT"
printf '%s\n' "Use this environment's vllm serve directly. No model was downloaded or loaded; full model/FP8 and multi-GPU serving remain to be validated."
